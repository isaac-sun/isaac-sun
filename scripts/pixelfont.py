GLYPHS = {k: [row for row in v.split("|")] for k, v in _G.items()}


def width(s, scale):
    return len(s) * 6 * scale - scale


def pixel_text(x, y, s, scale, fill, anchor="start", extra=""):
    """Render s with its top-left at (x, y); each font pixel is scale×scale."""
    s = s.upper()
    if anchor == "middle":
        x -= width(s, scale) / 2
    elif anchor == "end":
        x -= width(s, scale)
    d = []
    for i, ch in enumerate(s):
        rows = GLYPHS.get(ch, GLYPHS["?"])
        gx = x + i * 6 * scale
        for r, row in enumerate(rows):
            c = 0
            while c < 5:
                if row[c] == "#":
                    run = 1
                    while c + run < 5 and row[c + run] == "#":
                        run += 1
                    d.append(f"M{gx + c * scale:g} {y + r * scale:g}h{run * scale:g}v{scale:g}h{-run * scale:g}z")
                    c += run
                else:
                    c += 1
    return f'<path d="{"".join(d)}" fill="{fill}" {extra}/>'


def sprite(x, y, rows, palette, scale):
    """Draw a pixel sprite from strings; '.' is transparent."""
    out = []
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch != ".":
                out.append(f'<rect x="{x + c * scale}" y="{y + r * scale}" width="{scale}" height="{scale}" fill="{palette[ch]}"/>')
    return "\n".join(out)
